import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {createRuntime,uid} from './core.js';
import express from '../src/browser/express.js';
import {migrateWorkflow} from '../src/shared/workflow.js';
const runtime=await createRuntime({db:new PGlite(),express,schema:await fs.readFile(new URL('./schema.sql',import.meta.url),'utf8')});
let count=0;
const check=(a,b,label)=>{assert.deepEqual(a,b,label);count++;console.log('PASS',label);};
const client=()=>{let cookie='';return async(url,{method='GET',body,headers={}}={})=>{const res=await runtime.app.request({url:'/api'+url,method,body:body===undefined?undefined:JSON.stringify(body),headers:{'X-Flowbase-Client':'web',cookie,...headers}});if(res.headers['set-cookie'])cookie=res.headers['set-cookie'];return res;};};
const drain=async()=>{for(let i=0;i<20;i++)await runtime.processEvents();};
try{
 const owner=client(),manager=client(),other=client();
 let s=(await owner('/state')).data;const app=s.app.id;
 check(s.records.length,23,'Browser bridge seeds CRM');
 check((await owner('/apps/'+app+'/records',{method:'POST',headers:{'X-Flowbase-Client':'bad'},body:{}})).status,403,'Browser bridge applies middleware');
 check((await owner('/records/invalid',{method:'PATCH',body:{}})).status,422,'Browser bridge parses params and PATCH errors');
 check((await owner('/missing')).status,404,'Browser bridge returns unknown endpoint');
 const d=structuredClone(s.draft.definition);d.workflows=d.workflows.map(migrateWorkflow);
 const save=await owner('/apps/'+app+'/draft',{method:'PUT',body:{definition:d,revision:s.draft.revision}});
 check(save.status,200,'Browser bridge saves graph draft');
 check((await owner('/apps/'+app+'/publish',{method:'POST',body:{revision:save.data.revision}})).status,200,'Browser bridge publishes graph');
 const account=s.records.find(r=>r.entity_key==='account');
 const made=await owner('/apps/'+app+'/records',{method:'POST',body:{entity:'opportunity',data:{name:'Browser test deal',amount:'1000000',discount_percent:'15'},references:{account:account.id}}});
 check(made.status,200,'Browser bridge creates record');
 const id=made.data.id;
 check((await owner('/records/'+id,{method:'PATCH',body:{revision:1,data:{name:'Browser updated deal'}}})).status,200,'Browser bridge updates record');
 const started=await owner('/records/'+id+'/start',{method:'POST',body:{workflowKey:d.workflows[0].key,revision:2},headers:{'Idempotency-Key':'browser-graph'}});
 check(started.status,200,'Browser bridge starts graph');await drain();
 await manager('/demo-session',{method:'POST',body:{userId:uid(4),tenantId:uid(1)}});
 const task=(await manager('/state')).data.approvals.find(t=>t.run_id===started.data.id);
 check(Boolean(task),true,'Browser worker reaches approval task');
 check((await manager('/approvals/'+task.id+'/decision',{method:'POST',body:{decision:'approved'}})).status,200,'Browser bridge switches persona and approves');await drain();
 s=(await owner('/state?app='+app)).data;
 check(s.runs.find(r=>r.id===started.data.id).status,'completed','Browser graph completes');
 check(s.records.find(r=>r.id===id).data.discount_status,'approved','Browser data task updates record');
 await other('/demo-session',{method:'POST',body:{userId:uid(3),tenantId:uid(2)}});
 check((await other('/runs/'+started.data.id+'/cancel',{method:'POST',body:{}})).status,404,'Browser runtime maintains tenant scope');
 console.log('\n'+count+' browser bridge assertions passed.');
}finally{await runtime.close();}
